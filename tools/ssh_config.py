#!/usr/bin/env python3
"""Generate the ssh config for the companions from companions.yaml.

    python3 tools/ssh_config.py                 # print it
    python3 tools/ssh_config.py --install       # write ~/.ssh/config.d/drone-dev
    python3 tools/ssh_config.py --check         # does the live config match?

WHY. Every tool in this repo addresses the companions by name -- `jetson-1`, `jetson-2`.
Until 12 Oct 2026 those names existed only in one person's ~/.ssh/config on one
workstation, so a second or rebuilt ground station could reach no aircraft at all until
somebody remembered the addressing and retyped it. The repo is now the source of truth.

--install writes a separate file and adds one Include line to ~/.ssh/config rather than
editing the body of it, so your own hosts are never touched and the generated block can
be regenerated or deleted without collateral damage. Include must appear BEFORE any
`Host *` section, because ssh takes the FIRST value it finds for each keyword -- a
trailing Include is silently overridden by anything matched earlier.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / "companions.yaml"
INCLUDE_DIR = Path.home() / ".ssh" / "config.d"
INCLUDE_FILE = INCLUDE_DIR / "drone-dev"
SSH_CONFIG = Path.home() / ".ssh" / "config"
INCLUDE_LINE = f"Include {INCLUDE_FILE}"


def render(spec: dict) -> str:
    user = spec.get("user", "root")
    identity = spec.get("identity", "~/.ssh/id_ed25519")
    out = [
        "# Generated by tools/ssh_config.py from companions.yaml -- do not edit by hand.",
        "# Regenerate after changing that file.",
        "",
    ]
    names = []
    for name, c in spec.get("companions", {}).items():
        names.append(name)
        out += [f"Host {name}", f"    HostName {c['ip']}"]
        if c.get("aircraft"):
            out[-2] = f"Host {name}          # {c['aircraft']} (sysid {c.get('sysid')})"
        out.append("")
    for name, ip in (spec.get("legacy_lan") or {}).items():
        names.append(name)
        out += [f"Host {name}", f"    HostName {ip}", ""]
    if names:
        out += [
            f"Host {' '.join(names)}",
            f"    User {user}",
            f"    IdentityFile {identity}",
            "    IdentitiesOnly yes",
            "    StrictHostKeyChecking accept-new",
            # A companion that drops off the network must fail fast, not hang a script
            # for the TCP default of ~2 minutes.
            "    ConnectTimeout 10",
            "    ServerAliveInterval 5",
            "    ServerAliveCountMax 3",
            "",
        ]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--install", action="store_true",
                    help=f"write {INCLUDE_FILE} and reference it from ~/.ssh/config")
    ap.add_argument("--check", action="store_true",
                    help="compare the installed block with what this file would generate")
    args = ap.parse_args()

    spec = yaml.safe_load(CONFIG.read_text())
    text = render(spec)

    if args.check:
        if not INCLUDE_FILE.exists():
            print(f"[ssh] {INCLUDE_FILE} does not exist -- run --install", file=sys.stderr)
            return 1
        if INCLUDE_FILE.read_text() != text:
            print(f"[ssh] {INCLUDE_FILE} is STALE -- rerun --install", file=sys.stderr)
            return 1
        if INCLUDE_LINE not in SSH_CONFIG.read_text():
            print(f"[ssh] ~/.ssh/config has no '{INCLUDE_LINE}'", file=sys.stderr)
            return 1
        print("[ssh] installed config matches companions.yaml")
        return 0

    if not args.install:
        print(text, end="")
        return 0

    INCLUDE_DIR.mkdir(parents=True, exist_ok=True)
    INCLUDE_FILE.write_text(text)
    INCLUDE_FILE.chmod(0o600)
    print(f"[ssh] wrote {INCLUDE_FILE}", file=sys.stderr)

    existing = SSH_CONFIG.read_text() if SSH_CONFIG.exists() else ""
    if INCLUDE_LINE in existing:
        print("[ssh] ~/.ssh/config already includes it", file=sys.stderr)
    else:
        SSH_CONFIG.parent.mkdir(parents=True, exist_ok=True)
        SSH_CONFIG.write_text(f"{INCLUDE_LINE}\n\n{existing}")
        SSH_CONFIG.chmod(0o600)
        print(f"[ssh] prepended '{INCLUDE_LINE}' to {SSH_CONFIG}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
